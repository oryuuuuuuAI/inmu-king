const toKeyframe = (r) => Object.freeze({
  beat: r[0],
  section: r[1],
  pose: Object.freeze({
    armL: { upper: r[2], lower: r[3], hand: HAND[r[4]] },
    armR: { upper: r[5], lower: r[6], hand: HAND[r[7]] },
    legL: { thigh: r[8], shin: r[9], lift: r[10] },
    legR: { thigh: r[11], shin: r[12], lift: r[13] },
    body: { tilt: r[14], dx: r[15], dy: r[16], facing: FACING[r[17]] },
  }),
})

/** 全員そろった振付。 */
export const KEYFRAMES = Object.freeze(RAW.map(toKeyframe))

/** 経過ミリ秒 → 1 周の中の拍(LOOP_START 以上 LOOP_START + LOOP_BEATS 未満)。speed は 1 = 原曲の速さ。 */
export function beatAt(elapsedMs, speed = 1) {
  return wrapBeat(LOOP_START + (Math.max(0, elapsedMs) / 1000) * (BPM / 60) * speed)
}

/** beatAt の逆: 拍 → その拍になるまでの経過時間(ms)。速さを変えても今の拍から続けるのに使う。 */
export function elapsedAt(beat, speed = 1) {
  return ((wrapBeat(beat) - LOOP_START) / (BPM / 60) / speed) * 1000
}

/** 拍を 1 周の中(LOOP_START 以上 LOOP_START + LOOP_BEATS 未満)へ折り返す。 */
export function wrapBeat(beat) {
  return LOOP_START + ((((beat - LOOP_START) % LOOP_BEATS) + LOOP_BEATS) % LOOP_BEATS)
}

/** 拍 → 区間とカウント(1〜8)。 */
export function countAt(beat) {
  beat = wrapBeat(beat)
  let section = SECTIONS[0]
  for (const s of SECTIONS) if (beat >= s.start) section = s
  const count = ((Math.floor(beat) % 8) + 8) % 8 + 1
  return { section: section.name, label: section.label, count }
}

const smooth = (u) => u * u * (3 - 2 * u)

/** 角度の補間: ふつうは近い回りで、ほぼ反対向き(170 度以上)のときは真下を通る回りで。終わり(u = 1)は b そのもの。 */
function lerpAngle(a, b, u) {
  if (u >= 1) return b
  let d = ((b - a + 540) % 360) - 180
  if (Math.abs(d) >= 170) d = b - a
  return a + d * u
}

const lerp = (a, b, u) => a + (b - a) * u

/** 傾きの補間: 近い回りで(360 → 0 のような 1 回転ぶんの差では回らない)。ちょうど反対向きのときは数の差どおりに回す。
 *  終わり(u = 1)は b そのもの(360 と 0 は同じ向き。数を次のキーフレームにそろえる)。 */
function lerpTilt(a, b, u) {
  if (u >= 1) return b
  let d = ((b - a + 540) % 360) - 180
  if (Math.abs(d) === 180) d = b - a
  return a + d * u
}

/** キーフレームの並び(拍の順)→ 拍 b のポーズ(前後のキーフレームのあいだを、なめらかにつなぐ)。 */
function interpolate(keys, b) {
  let i = 0
  while (i < keys.length - 2 && keys[i + 1].beat <= b) i++
  const k0 = keys[i]
  const k1 = keys[i + 1]
  const u = smooth(Math.min(1, Math.max(0, (b - k0.beat) / (k1.beat - k0.beat))))
  const p = k0.pose
  const q = k1.pose
  const pick = (x, y) => (u < 0.5 ? x : y)
  const arm = (x, y) => ({ upper: lerpAngle(x.upper, y.upper, u), lower: lerpAngle(x.lower, y.lower, u), hand: pick(x.hand, y.hand) })
  const leg = (x, y) => ({ thigh: lerpAngle(x.thigh, y.thigh, u), shin: lerpAngle(x.shin, y.shin, u), lift: lerp(x.lift, y.lift, u) })
  return {
    armL: arm(p.armL, q.armL),
    armR: arm(p.armR, q.armR),
    legL: leg(p.legL, q.legL),
    legR: leg(p.legR, q.legR),
    body: {
      tilt: lerpTilt(p.body.tilt, q.body.tilt, u),
      dx: lerp(p.body.dx, q.body.dx, u),
      dy: lerp(p.body.dy, q.body.dy, u),
      facing: pick(p.body.facing, q.body.facing),
    },
  }
}

// 1 人だけ違う動きの区間(画面の左から 0〜4)。from〜to のあいだだけ、共通の振付の代わりに使う。
// from と to のポーズは共通の振付のその拍のポーズにする(つなぎ目で飛ばない)。
export const SOLOS = Object.freeze(Object.fromEntries(Object.entries(SOLO_RAW).map(([d, segs]) => [d, Object.freeze(segs.map((seg) => {
  const ends = (beat) => Object.freeze({ beat, section: countAt(beat).section, pose: Object.freeze(interpolate(KEYFRAMES, beat)) })
  return Object.freeze({
    dancer: Number(d),
    from: seg.from,
    to: seg.to,
    label: seg.label,
    keys: Object.freeze([ends(seg.from), ...seg.rows.map(toKeyframe), ends(seg.to)]),
  })
}))])))

/** 拍 → ポーズ。dancer(画面の左から 0〜4)を渡すと、その人だけ違う区間ではその人のポーズ。 */
export function poseAt(beat, dancer) {
  const b = wrapBeat(beat)
  const seg = soloAt(b, dancer)
  return interpolate(seg ? seg.keys : KEYFRAMES, b)
}

/** 拍 → 5 体ぶんのポーズ(画面の左から)。共通の振付の人は同じ物を指す(絵を 1 度だけ描くため)。 */
export function posesAt(beat) {
  const b = wrapBeat(beat)
  const common = interpolate(KEYFRAMES, b)
  const out = []
  for (let d = 0; d < DANCERS; d++) {
    const seg = soloAt(b, d)
    out.push(seg ? interpolate(seg.keys, b) : common)
  }
  return out
}

function soloAt(b, dancer) {
  const segs = dancer === undefined ? undefined : SOLOS[dancer]
  if (!segs) return undefined
  for (const seg of segs) if (b >= seg.from && b <= seg.to) return seg
  return undefined
}
